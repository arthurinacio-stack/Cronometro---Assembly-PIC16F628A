#INCLUDE <P16F628A.INC>
__CONFIG _BODEN_ON & _CP_OFF & _PWRTE_ON & _WDT_OFF & _LVP_OFF & _MCLRE_ON & _XT_OSC


TIQUES      EQU 0x20
UNIDADE     EQU 0x21
DEZENA      EQU 0x22
DELAYVAR    EQU 0x23

W_TEMP      EQU 0x24
STATUS_TEMP EQU 0x25


ORG 0x0000
GOTO INICIO


ORG 0x0004

    MOVWF W_TEMP
    SWAPF STATUS,W
    MOVWF STATUS_TEMP

    BCF INTCON,T0IF

    MOVLW D'131'
    MOVWF TMR0

    DECFSZ TIQUES,F
    GOTO RESTAURA

    MOVLW D'125'
    MOVWF TIQUES

    INCF UNIDADE,F

    MOVF UNIDADE,W
    XORLW D'10'
    BTFSS STATUS,Z
    GOTO RESTAURA

    CLRF UNIDADE
    INCF DEZENA,F

    MOVF DEZENA,W
    XORLW D'10'
    BTFSS STATUS,Z
    GOTO RESTAURA

    CLRF DEZENA

RESTAURA
    SWAPF STATUS_TEMP,W
    MOVWF STATUS

    SWAPF W_TEMP,F
    SWAPF W_TEMP,W

    RETFIE


; TABELA DEZENA

TABELA_DEZENA
    ADDWF PCL,F

    RETLW B'11101110'
    RETLW B'00101000'
    RETLW B'11001101'
    RETLW B'01101101'
    RETLW B'00101011'
    RETLW B'01100111'
    RETLW B'11100111'
    RETLW B'00101100'
    RETLW B'11101111'
    RETLW B'00101111'


; TABELA UNIDADE

TABELA_UNIDADE
    ADDWF PCL,F

    RETLW B'11111110'
    RETLW B'00111000'
    RETLW B'11011101'
    RETLW B'01111101'
    RETLW B'00111011'
    RETLW B'01110111'
    RETLW B'11110111'
    RETLW B'00111100'
    RETLW B'11111111'
    RETLW B'00111111'


DELAY
    MOVLW D'150'
    MOVWF DELAYVAR

D1
    DECFSZ DELAYVAR,F
    GOTO D1
    RETURN


INICIO

    CLRF PORTA
    CLRF PORTB

    MOVLW D'7'
    MOVWF CMCON

    BANKSEL OPTION_REG
    MOVLW B'10000101'
    MOVWF OPTION_REG

    BANKSEL INTCON
    MOVLW B'10100000'
    MOVWF INTCON

    BANKSEL TMR0
    MOVLW D'131'
    MOVWF TMR0

    MOVLW D'125'
    MOVWF TIQUES

    CLRF UNIDADE
    CLRF DEZENA


; RA0 -> display dezena
; RA1 -> display unidade
; RA2 -> botão reset

    BANKSEL TRISA
    MOVLW B'00000100'
    MOVWF TRISA

    CLRF TRISB

    BANKSEL PORTA
    CLRF PORTA
    CLRF PORTB


LOOP


    BTFSC PORTA,2
    GOTO MOSTRAR

    CLRF UNIDADE
    CLRF DEZENA

    MOVLW D'125'
    MOVWF TIQUES

MOSTRAR


; MOSTRA DEZENA

    BCF PORTA,0
    BCF PORTA,1

    MOVF DEZENA,W
    CALL TABELA_DEZENA
    MOVWF PORTB

    BSF PORTA,0
    CALL DELAY


; MOSTRA UNIDADE

    BCF PORTA,0
    BCF PORTA,1

    MOVF UNIDADE,W
    CALL TABELA_UNIDADE
    MOVWF PORTB

    BSF PORTA,1
    CALL DELAY

    GOTO LOOP

END